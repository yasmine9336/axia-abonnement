export default function Sidebar() {
  const { user, logout } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();
  const [profileImageUrl, setProfileImageUrl] = useState<string | null>(null);
  const { unreadMessages, unreadChat, resetUnreadMessages, resetUnreadChat } = useNotifications();

  const accent = "var(--color-primary)";
  const accentBg = "bg-[var(--color-primary-soft)] text-[var(--color-primary)]";
  const accentIcon = "text-[var(--color-primary)]";
  const accentAvatar = "bg-[var(--color-primary)]";
  const accentLogout =
    "border-[var(--color-primary)] text-[var(--color-primary)] hover:bg-[var(--color-primary)] hover:text-white";

  const getPhotoUrl = (photoPath?: string | null) => {
    if (!photoPath) return null;
    if (photoPath.startsWith("http")) return photoPath;
    return `${API_URL}${photoPath}`;
  };

  useEffect(() => {
    const fetchProfilePhoto = async () => {
      try {
        const res = await axiosInstance.get("/profile");
        setProfileImageUrl(res.data?.profileImageUrl ?? null);
      } catch {
        setProfileImageUrl(null);
      }
    };
    fetchProfilePhoto();
  }, []);

  const navItems =
    user?.role === "Admin" ? adminNav : user?.role === "Responsable" ? responsableNav : clientNav;

  const handleLogout = () => {
    logout();
    navigate("/login");
  };

  const getInitial = () => user?.username?.charAt(0).toUpperCase() || "U";

  const profilePhoto = getPhotoUrl(profileImageUrl);

  return (
    <aside className="w-64 min-h-screen bg-white border-r border-gray-200 flex flex-col">
      <div className="p-6 border-b border-gray-100">
        <h1 className="text-xl font-bold" style={{ color: accent }}>
          AxiaAbonnement
        </h1>

        <div className="mt-2">
          {user?.role === "Admin" ? (
            <span className="inline-flex items-center gap-1 bg-(--color-primary-soft) text-(--color-primary) text-xs font-bold px-2.5 py-1 rounded-full">
              <svg className="w-3 h-3" fill="currentColor" viewBox="0 0 20 20">
                <path
                  fillRule="evenodd"
                  d="M2.166 4.999A11.954 11.954 0 0010 1.944 11.954 11.954 0 0017.834 5c.11.65.166 1.32.166 2.001 0 5.225-3.34 9.67-8 11.317C5.34 16.67 2 12.225 2 7c0-.682.057-1.35.166-2.001zm11.541 3.708a1 1 0 00-1.414-1.414L9 10.586 7.707 9.293a1 1 0 00-1.414 1.414l2 2a1 1 0 001.414 0l4-4z"
                  clipRule="evenodd"
                />
              </svg>
              Portail Admin
            </span>
          ) : user?.role === "Responsable" ? (
            <span className="inline-flex items-center gap-1 bg-(--color-primary-soft) text-(--color-primary) text-xs font-semibold px-2.5 py-1 rounded-full">
              <svg className="w-3 h-3" fill="none" stroke="currentColor" strokeWidth={2} viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" d="M16 7a4 4 0 11-8 0 4 4 0 018 0zM12 14a7 7 0 00-7 7h14a7 7 0 00-7-7z" />
              </svg>
              Portail Responsable
            </span>
          ) : (
            <span className="inline-flex items-center gap-1 bg-(--color-primary-soft) text-(--color-primary) text-xs font-semibold px-2.5 py-1 rounded-full">
              <svg className="w-3 h-3" fill="none" stroke="currentColor" strokeWidth={2} viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" d="M16 7a4 4 0 11-8 0 4 4 0 018 0zM12 14a7 7 0 00-7 7h14a7 7 0 00-7-7z" />
              </svg>
              Portail Client
            </span>
          )}
        </div>
      </div>

      <nav className="flex-1 p-4 space-y-1">
        {navItems.map((item) => {
          const isActive = location.pathname === item.path;
          const isMessages = item.path.includes("messages");
          const isChat = item.path.includes("/chat");

          return (
            <button
              key={item.path}
              onClick={() => {
                navigate(item.path);
                if (isMessages) resetUnreadMessages();
                if (isChat) resetUnreadChat();
              }}
              className={`w-full flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium transition-colors ${
                isActive ? accentBg : "text-gray-600 hover:bg-gray-100"
              }`}
            >
              <span className={isActive ? accentIcon : "text-gray-400"}>{item.icon}</span>

              <span className="flex-1 text-left">{item.label}</span>

              {isMessages && unreadMessages > 0 && (
                <span className="w-5 h-5 bg-red-500 text-white text-xs font-bold rounded-full flex items-center justify-center">
                  {unreadMessages > 9 ? "9+" : unreadMessages}
                </span>
              )}

              {isChat && unreadChat > 0 && (
                <span className="w-5 h-5 bg-red-500 text-white text-xs font-bold rounded-full flex items-center justify-center">
                  {unreadChat > 9 ? "9+" : unreadChat}
                </span>
              )}
            </button>
          );
        })}
      </nav>

      <div className="p-4 border-t border-gray-100">
        <div className="flex items-center gap-3 mb-4">
          {profilePhoto ? (
            <img
              src={profilePhoto}
              alt="Photo profil"
              className="w-10 h-10 rounded-full object-cover border border-gray-200"
            />
          ) : (
            <div
              className={`w-10 h-10 rounded-full flex items-center justify-center text-white font-bold text-sm ${accentAvatar}`}
            >
              {getInitial()}
            </div>
          )}

          <div className="flex-1 min-w-0">
            <p className="text-sm font-semibold text-gray-900 truncate">{user?.username}</p>
            <p className="text-xs text-gray-500 truncate">{user?.email}</p>
          </div>
        </div>

        <button
          onClick={handleLogout}
          className={`w-full flex items-center justify-center gap-2 border font-semibold py-2.5 rounded-xl transition-colors text-sm ${accentLogout}`}
        >
          <svg className="w-4 h-4" fill="none" stroke="currentColor" strokeWidth={2} viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          Déconnexion
        </button>
      </div>
    </aside>
  );
}