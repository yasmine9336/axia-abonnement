export default function Sidebar() {
  const { user, logout } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();
  const [profileImageUrl, setProfileImageUrl] = useState<string | null>(null);

  const getPhotoUrl = (photoPath?: string | null) => {
    if (!photoPath) return null;
    if (photoPath.startsWith("http")) return photoPath;
    return `https://localhost:7000${photoPath}`;
  };

  useEffect(() => {
    const fetchProfilePhoto = async () => {
      try {
        const res = await axiosInstance.get("/profile");
        setProfileImageUrl(res.data?.profileImageUrl ?? null);
      } catch {
        setProfileImageUrl(null);
      }
    };

    fetchProfilePhoto();
  }, []);

  const navItems =
    user?.role === "Admin"
      ? adminNav
      : user?.role === "Responsable"
        ? responsableNav
        : clientNav;

  const portalLabel =
    user?.role === "Admin"
      ? "Portail Admin"
      : user?.role === "Responsable"
        ? "Portail Responsable"
        : "Portail Client";

  const handleLogout = () => {
    logout();
    navigate("/login");
  };

  const getInitial = () => {
    return user?.username?.charAt(0).toUpperCase() || "U";
  };

  useEffect(() => {
    const fetchProfilePhoto = async () => {
      try {
        const res = await axiosInstance.get("/profile");
        setProfileImageUrl(res.data?.profileImageUrl ?? null);
      } catch {
        setProfileImageUrl(null);
      }
    };

    fetchProfilePhoto();
  }, []);

  return (
    <aside className="w-64 min-h-screen bg-white border-r border-gray-200 flex flex-col">
      {/* Logo */}
      <div className="p-6 border-b border-gray-100">
        <h1 className="text-xl font-bold text-[#4F46E5]">AxiaAbonnement</h1>
        <p className="text-xs text-gray-500 mt-1">{portalLabel}</p>
      </div>

      {/* Navigation */}
      <nav className="flex-1 p-4 space-y-1">
        {navItems.map((item) => {
          const isActive = location.pathname === item.path;
          return (
            <button
              key={item.path}
              onClick={() => navigate(item.path)}
              className={`w-full flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium transition-colors ${
                isActive
                  ? "bg-[#4F46E5]/10 text-[#4F46E5]"
                  : "text-gray-600 hover:bg-gray-100"
              }`}
            >
              <span className={isActive ? "text-[#4F46E5]" : "text-gray-400"}>
                {item.icon}
              </span>
              {item.label}
            </button>
          );
        })}
      </nav>

      {/* User info + logout */}
      <div className="p-4 border-t border-gray-100">
        <div className="flex items-center gap-3 mb-4">
          {getPhotoUrl(profileImageUrl) ? (
            <img
              src={getPhotoUrl(profileImageUrl)!}
              alt="Photo profil"
              className="w-10 h-10 rounded-full object-cover border border-gray-200"
            />
          ) : (
            <div className="w-10 h-10 bg-[#4F46E5] rounded-full flex items-center justify-center text-white font-bold text-sm">
              {getInitial()}
            </div>
          )}
          <div className="flex-1 min-w-0">
            <p className="text-sm font-semibold text-gray-900 truncate">
              {user?.username}
            </p>
            <p className="text-xs text-gray-500 truncate">{user?.email}</p>
          </div>
        </div>
        <button
          onClick={handleLogout}
          className="w-full flex items-center justify-center gap-2 border border-[#4F46E5] text-[#4F46E5] hover:bg-[#4F46E5] hover:text-white font-semibold py-2.5 rounded-xl transition-colors text-sm"
        >
          <svg
            className="w-4 h-4"
            fill="none"
            stroke="currentColor"
            strokeWidth={2}
            viewBox="0 0 24 24"
          >
            <path
              strokeLinecap="round"
              strokeLinejoin="round"
              d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1"
            />
          </svg>
          Déconnexion
        </button>
      </div>
    </aside>
  );
}
