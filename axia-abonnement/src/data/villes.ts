// Fonction helper : retourne les villes d'un gouvernorat donné
export function getVillesByGouvernorat(gouvernorat: string): string[] {
  return VILLES_PAR_GOUVERNORAT[gouvernorat] ?? [];
}

// Fonction helper : vérifie si une ville appartient à un gouvernorat
export function isVilleInGouvernorat(ville: string, gouvernorat: string): boolean {
  return getVillesByGouvernorat(gouvernorat).includes(ville);
}